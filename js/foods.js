// f(name, kcal, protein, carbs, fat, unitGrams, unitName, extra)
//   unitGrams/unitName: what "1 <food>" or "1 <unitName> <food>" means, e.g. 1 egg = 50 g.
//   extra.aliases: other names that match this food.
//   extra.tags: used for diet/allergy filtering (meat, fish, dairy, egg, gluten, nuts, honey).
//   extra.cup / extra.tbsp: grams in one cup / tablespoon, when it differs from the default.
//   extra.splash: grams when added "with" something and no amount is given ("coffee with milk").

